// Targets the f32/f64 special values crossing the JS/Wasm boundary in both
// directions (spectec/document/js-api/index.bs):
//   - ToJSValue (wasm -> JS, :1386-1393): "If |f32| is [=+∞=] or [=−∞=],
//     return **+∞**<sub>𝔽</sub> or **-∞**<sub>𝔽</sub>, respectively." and
//     "If |f32| is [=nan=], return **NaN**." (f64 alike).
//   - ToWebAssemblyValue (JS -> wasm, :1431-1445): the "If |number| is
//     **NaN**" case, which builds a positive NaN with an implementation-defined
//     payload of at least canon_N (docs/spec_errors.md #43).
// Found via esmeta.wji.WjiCoverage's annotated IR: all of these sat at 0 hits,
// and returning an infinity from wasm crashed WJI outright.
//
// Confirmed against real Node 24.2.0.
function assertEq(actual, expected, msg) {
  if (actual !== expected)
    throw new Error(msg + ": expected " + expected + ", got " + actual);
}

