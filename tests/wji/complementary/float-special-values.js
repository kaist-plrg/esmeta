// wasm -> JS
assertEq(e.posInf32(), Infinity, "f32 +inf");
assertEq(e.negInf32(), -Infinity, "f32 -inf");
assertEq(Number.isNaN(e.nan32()), true, "f32 nan");
assertEq(e.posInf64(), Infinity, "f64 +inf");
assertEq(e.negInf64(), -Infinity, "f64 -inf");
assertEq(Number.isNaN(e.nan64()), true, "f64 nan (negative, non-canonical payload)");

// JS -> wasm, observed as raw bits inside wasm
assertEq(e.bits32(Infinity), 0x7f800000, "f32 +inf bits");
assertEq(e.bits32(-Infinity), 0xff800000 | 0, "f32 -inf bits");
const nan32 = e.bits32(NaN);
assertEq(nan32 > 0, true, "f32 NaN is positive");
assertEq((nan32 & 0x7fc00000) === 0x7fc00000, true, "f32 NaN payload is at least canon_32");
assertEq(e.bits64(Infinity), 0x7ff0000000000000n, "f64 +inf bits");
assertEq(e.bits64(-Infinity), -0x10000000000000n, "f64 -inf bits");
const nan64 = e.bits64(NaN);
assertEq(nan64 > 0n, true, "f64 NaN is positive");
assertEq((nan64 >> 51n) === 0xfffn, true, "f64 NaN payload is at least canon_64");

