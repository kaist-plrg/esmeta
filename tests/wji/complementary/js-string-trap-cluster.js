function assertTraps(fn, msg) {
  try {
    fn();
  } catch (e) {
    assertEq(e instanceof WebAssembly.RuntimeError, true, msg + ": expected a RuntimeError");
    return;
  }
  throw new Error(msg + ": expected a trap, got none");
}

assertTraps(() => exports.intoCharCodeArray("hi", null, 0), "intoCharCodeArray with a null array");
assertTraps(() => exports.codePointAt("hi", 10), "codePointAt with an out-of-bounds index");
assertTraps(() => exports.fromCodePoint(0x110000), "fromCodePoint with a code point past 0x10FFFF");

// sanity: the non-trapping paths still work (same functions, valid inputs).
assertEq(exports.codePointAt("hi", 0), "h".codePointAt(0), "codePointAt with a valid index");
assertEq(exports.fromCodePoint(65) !== undefined, true, "fromCodePoint with a valid code point");

