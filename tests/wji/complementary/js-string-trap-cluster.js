// Targets three "wasm trap" branches across the js-string builtins proposal
// that the official corpus never exercises, found via esmeta.wji.WjiCoverage:
//
// 1. intoCharCodeArray: the target array reference is null (spectec/document/
//    js-api/index.bs's own `js-string-intoCharCodeArray` -- "If array is
//    null, throw a RuntimeError exception as if a trap was executed.").
// 2. codePointAt: index >= the string's length (index.bs:2076-2080).
// 3. fromCodePoint: the code point exceeds 0x10FFFF (index.bs).
//
// Each is called directly on a WebAssembly function that imports the
// corresponding "wasm:js-string" builtin and forwards its own arguments to
// it -- the same construction `spectec/test/js-api/js-string/basic.any.js`'s
// own setup() uses (WasmModuleBuilder, not wat2wasm -- this proposal's
// `(ref null $arrayIndex)`/externref signatures aren't expressible in plain
// WAT text without the same builder machinery anyway). The bytes below were
// generated by running `spectec/test/js-api/wasm-module-builder.js` under
// Node's `vm` module (sandboxed eval, since the file is a plain script that
// expects to run in a global scope, not a module) and serializing a module
// that imports exactly these three builtins and re-exports one wrapper
// function per builtin.
//
// Confirmed against real Node 24.2.0: all three throw a WebAssembly.
// RuntimeError (trap), not a TypeError/RangeError -- these are genuine wasm
// traps, not JS-level exceptions.
//
// NOT covered here (left as a documented gap, personal/TODO.md #71): a
// *negative* index (e.g. `codePointAt(-1)`) crashes the interpreter outright
// instead of trapping -- a real bug, not something a passing test should
// assert.
function assertEq(actual, expected, msg) {
  if (actual !== expected)
    throw new Error(msg + ": expected " + expected + ", got " + actual);
}

