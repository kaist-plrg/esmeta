// The memory.grow hook (index.bs, "Immediately after a WebAssembly memory.grow
// |x| instruction executes") refreshes the buffer whenever the instruction does
// not return -1, even when the size does not change: a successful
// memory.grow 0 detaches a fixed-length buffer. A failing grow (-1) does not.
// Node 26.12.1, d8, SpiderMonkey and JSC all behave this way.
const bytes = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0b, 0x02, 0x60,
  0x01, 0x7f, 0x01, 0x7f, 0x60, 0x02, 0x7f, 0x7f, 0x00, 0x03, 0x04, 0x03,
  0x00, 0x01, 0x00, 0x05, 0x04, 0x01, 0x01, 0x01, 0x04, 0x07, 0x2c, 0x04,
  0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x08, 0x77, 0x61,
  0x73, 0x6d, 0x47, 0x72, 0x6f, 0x77, 0x00, 0x00, 0x09, 0x77, 0x61, 0x73,
  0x6d, 0x57, 0x72, 0x69, 0x74, 0x65, 0x00, 0x01, 0x08, 0x77, 0x61, 0x73,
  0x6d, 0x52, 0x65, 0x61, 0x64, 0x00, 0x02, 0x0a, 0x1a, 0x03, 0x06, 0x00,
  0x20, 0x00, 0x40, 0x00, 0x0b, 0x09, 0x00, 0x20, 0x00, 0x20, 0x01, 0x36,
  0x02, 0x00, 0x0b, 0x07, 0x00, 0x20, 0x00, 0x28, 0x02, 0x00, 0x0b
]);

function assertEq(actual, expected, msg) {
  if (actual !== expected)
    throw new Error(msg + ": expected " + expected + ", got " + actual);
}

WebAssembly.instantiate(bytes.buffer, {}).then(({ instance }) => {
  const memory = instance.exports.memory;

  const before = memory.buffer;
  assertEq(instance.exports.wasmGrow(0), 1, "memory.grow 0 returns the old size");
  assertEq(before.byteLength, 0, "old buffer detached after memory.grow 0");
  assertEq(memory.buffer === before, false, "fresh buffer after memory.grow 0");

  const kept = memory.buffer;
  assertEq(instance.exports.wasmGrow(100), -1, "memory.grow beyond maximum fails");
  assertEq(memory.buffer === kept, true, "buffer kept after a failing memory.grow");
  assertEq(kept.byteLength, 65536, "buffer still attached after a failing memory.grow");

  globalThis.__wjiOk = true;
});
