// global-mutation.wat: exports a mutable i32 global `g`, plus
// wasmSetGlobal(value)/wasmGetGlobal(). Verifies global mutation crosses the
// JS/wasm boundary in both directions.
const bytes = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x09, 0x02, 0x60,
  0x01, 0x7f, 0x00, 0x60, 0x00, 0x01, 0x7f, 0x03, 0x03, 0x02, 0x00, 0x01,
  0x06, 0x06, 0x01, 0x7f, 0x01, 0x41, 0x0a, 0x0b, 0x07, 0x25, 0x03, 0x01,
  0x67, 0x03, 0x00, 0x0d, 0x77, 0x61, 0x73, 0x6d, 0x53, 0x65, 0x74, 0x47,
  0x6c, 0x6f, 0x62, 0x61, 0x6c, 0x00, 0x00, 0x0d, 0x77, 0x61, 0x73, 0x6d,
  0x47, 0x65, 0x74, 0x47, 0x6c, 0x6f, 0x62, 0x61, 0x6c, 0x00, 0x01, 0x0a,
  0x0d, 0x02, 0x06, 0x00, 0x20, 0x00, 0x24, 0x00, 0x0b, 0x04, 0x00, 0x23,
  0x00, 0x0b,
]);

function assertEq(actual, expected, msg) {
  if (actual !== expected)
    throw new Error(msg + ": expected " + expected + ", got " + actual);
}

WebAssembly.instantiate(bytes.buffer, {}).then(({module, instance}) => {
  // JS -> wasm: JS sets the exported mutable global, wasm reads it back
  // through global.get.
  instance.exports.g.value = 123;
  const fromJs = instance.exports.wasmGetGlobal();
  assertEq(fromJs, 123, "JS write to global not visible to wasm");

  // wasm -> JS: wasm mutates its own global, JS observes it through .value.
  instance.exports.wasmSetGlobal(456);
  const fromWasm = instance.exports.g.value;
  assertEq(fromWasm, 456, "wasm write to global not visible to JS");

  globalThis.__wjiOk = true;
}).catch(e => print("uncaught: " + e));
