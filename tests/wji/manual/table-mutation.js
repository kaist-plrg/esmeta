// table-mutation.wat: exports a 2-slot funcref table (slot 0 pre-populated
// via an active element segment), wasmCallTable(index), and jsFnHandle (a
// re-export of the imported jsFn, giving JS a funcref-legal handle to its
// own function -- ToWebAssemblyValue rejects a plain closure). Verifies
// table mutation crosses the JS/wasm boundary in both directions.
const bytes = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0a, 0x02, 0x60,
  0x00, 0x01, 0x7f, 0x60, 0x01, 0x7f, 0x01, 0x7f, 0x02, 0x0c, 0x01, 0x03,
  0x65, 0x6e, 0x76, 0x04, 0x6a, 0x73, 0x46, 0x6e, 0x00, 0x00, 0x03, 0x03,
  0x02, 0x00, 0x01, 0x04, 0x05, 0x01, 0x70, 0x01, 0x02, 0x02, 0x07, 0x26,
  0x03, 0x0a, 0x6a, 0x73, 0x46, 0x6e, 0x48, 0x61, 0x6e, 0x64, 0x6c, 0x65,
  0x00, 0x00, 0x05, 0x74, 0x61, 0x62, 0x6c, 0x65, 0x01, 0x00, 0x0d, 0x77,
  0x61, 0x73, 0x6d, 0x43, 0x61, 0x6c, 0x6c, 0x54, 0x61, 0x62, 0x6c, 0x65,
  0x00, 0x02, 0x09, 0x07, 0x01, 0x00, 0x41, 0x00, 0x0b, 0x01, 0x01, 0x0a,
  0x0e, 0x02, 0x04, 0x00, 0x41, 0x2a, 0x0b, 0x07, 0x00, 0x20, 0x00, 0x11,
  0x00, 0x00, 0x0b,
]);

function assertEq(actual, expected, msg) {
  if (actual !== expected)
    throw new Error(msg + ": expected " + expected + ", got " + actual);
}

const importObject = { env: { jsFn: () => 99 } };

WebAssembly.instantiate(bytes.buffer, importObject).then(
  ({ module, instance }) => {
    const table = instance.exports.table;

    // wasm -> JS: an active element segment placed a wasm function at
    // table[0], JS observes it directly through table.get and calls it.
    const fromWasm = table.get(0)();
    assertEq(fromWasm, 42, "wasm-populated table slot not visible to JS");

    // JS -> wasm: JS sets a table slot directly with a wasm-wrapped handle
    // to its own function, wasm invokes it through call_indirect.
    table.set(1, instance.exports.jsFnHandle);
    const fromJs = instance.exports.wasmCallTable(1);
    assertEq(fromJs, 99, "JS-set table slot not visible to wasm");

    globalThis.__wjiOk = true;
  },
).catch(e => print("uncaught: " + e));
