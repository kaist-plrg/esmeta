// memory-mutation.wat: exports a 1-page memory, wasmWrite(offset, value),
// and wasmRead(offset). Verifies memory mutation crosses the JS/wasm
// boundary in both directions.
const bytes = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00, 0x01, 0x0b, 0x02, 0x60,
  0x02, 0x7f, 0x7f, 0x00, 0x60, 0x01, 0x7f, 0x01, 0x7f, 0x03, 0x03, 0x02,
  0x00, 0x01, 0x05, 0x03, 0x01, 0x00, 0x01, 0x07, 0x21, 0x03, 0x06, 0x6d,
  0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00, 0x09, 0x77, 0x61, 0x73, 0x6d,
  0x57, 0x72, 0x69, 0x74, 0x65, 0x00, 0x00, 0x08, 0x77, 0x61, 0x73, 0x6d,
  0x52, 0x65, 0x61, 0x64, 0x00, 0x01, 0x0a, 0x13, 0x02, 0x09, 0x00, 0x20,
  0x00, 0x20, 0x01, 0x36, 0x02, 0x00, 0x0b, 0x07, 0x00, 0x20, 0x00, 0x28,
  0x02, 0x00, 0x0b,
]);

function assertEq(actual, expected, msg) {
  if (actual !== expected)
    throw new Error(msg + ": expected " + expected + ", got " + actual);
}

WebAssembly.instantiate(bytes.buffer, {}).then(({module, instance}) => {
  const memory = instance.exports.memory;

  // wasm -> JS: wasm writes into its own memory, JS observes it directly
  // through the exported buffer.
  instance.exports.wasmWrite(0, 42);
  const fromWasm = new Int32Array(memory.buffer)[0];
  assertEq(fromWasm, 42, "wasm write not visible to JS");

  // JS -> wasm: JS writes directly into the buffer, wasm reads it back
  // through a load instruction.
  new Int32Array(memory.buffer)[1] = 99;
  const fromJs = instance.exports.wasmRead(4);
  assertEq(fromJs, 99, "JS write not visible to wasm");

  globalThis.__wjiOk = true;
}).catch(e => print("uncaught: " + e));
